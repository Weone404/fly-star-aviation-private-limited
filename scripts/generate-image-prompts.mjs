/**
 * Generate BLOG-IMAGE-PROMPTS.md from src/lib/blogImages.js.
 *
 * The prompts used to live in the markdown and the filenames in the code, which
 * meant the two drifted the moment anyone renamed a file. Now the code is the
 * source and this file is a printout of it: paste a prompt into your image tool,
 * save the result at the path the entry names, flip `ready` to true.
 *
 * Run: npm run image-prompts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BLOG_IMAGES, HOUSE_STYLE } from "../src/lib/blogImages.js";
import { STATIC_BLOG_POSTS } from "../src/lib/blogData.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "BLOG-IMAGE-PROMPTS.md");

const titleOf = (slug) => STATIC_BLOG_POSTS.find((p) => p.slug === slug)?.title || slug;

const all = Object.values(BLOG_IMAGES).flat();
const done = all.filter((i) => i.ready).length;

const lines = [
  "# Blog image prompts",
  "",
  "**Generated by `scripts/generate-image-prompts.mjs` — do not edit this file.**",
  "Edit `src/lib/blogImages.js` and run `npm run image-prompts`.",
  "",
  `${all.length} images planned across ${Object.keys(BLOG_IMAGES).length} posts. ${done} generated, ${all.length - done} outstanding.`,
  "",
  "## How to use this",
  "",
  "1. Copy a prompt below — it already ends with the house style line — into ChatGPT, or any image model.",
  "2. Save the result at the exact path the entry gives, under `public/`.",
  "3. Set `ready: true` on that entry in `src/lib/blogImages.js`.",
  "4. Re-run `npm run image-prompts` so the counts above stay honest.",
  "",
  "Until step 3, the image renders **nothing in production** and a placeholder carrying its own prompt in `npm run dev`. A missing picture is a gap; a broken image on a page whose whole claim is that its figures are checked is a defect.",
  "",
  "**Why no text in any image.** Generated lettering is reliably almost-right, and an almost-right number in an illustration is exactly the failure this site exists to avoid. Every figure on these pages is stated in the prose, where it is sourced.",
  "",
  "### House style, appended to every prompt",
  "",
  "> " + HOUSE_STYLE,
  "",
  "---",
  "",
];

for (const [slug, images] of Object.entries(BLOG_IMAGES)) {
  lines.push(`## ${titleOf(slug)}`, "", `\`/blog/${slug}\` — ${images.length} images`, "");
  images.forEach((img, i) => {
    const place =
      img.slot === "cover" ? "Cover" : `Inline, after heading ${img.after ?? "—"}`;
    lines.push(
      `### ${i + 1}. ${place}${img.ready ? " ✅ generated" : ""}`,
      "",
      `- **Save to:** \`public${img.file}\``,
      `- **Alt text:** ${img.alt}`,
      ...(img.caption ? [`- **Caption:** ${img.caption}`] : []),
      "",
      "```",
      `${img.prompt} ${HOUSE_STYLE}`,
      "```",
      "",
    );
  });
  lines.push("---", "");
}

fs.writeFileSync(OUT, lines.join("\n"));
console.log(`[image-prompts] ${all.length} prompts written to BLOG-IMAGE-PROMPTS.md (${all.length - done} outstanding)`);
